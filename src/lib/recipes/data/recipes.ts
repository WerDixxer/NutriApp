import type { RecipeUnit } from "../types";

/**
 * Die 60 mitgelieferten Rezepte (source.type = "internal"). Zutaten verweisen
 * per `food` (Slug aus data/foods.ts) auf die zentrale Food-Tabelle; Mengen,
 * Zutatenlisten und Tags stammen aus dem Auftrag. Nicht aus dem Auftrag,
 * sondern hier ergänzt (und im Abschlussbericht benannt):
 *  - Beschreibung, Anleitung (außer #1 und #2 als Vorlage), Zeiten,
 *    Küche, Equipment,
 *  - Portionen = 1 (nur #1 nennt sie ausdrücklich; alle Mengen sind
 *    erkennbar für eine Portion ausgelegt),
 *  - Lagerdauer nur bei gekochten Meal-Prep-Gerichten (konservativ 3 Tage im
 *    Kühlschrank), nie bei unklarer Haltbarkeit.
 * Nährwerte stehen NICHT hier: sie werden aus den Zutaten berechnet
 * (recipes/nutrition.ts) und beim Seeden als Snapshot gespeichert.
 */
export interface IngredientSeed {
  food: string;
  amount?: number;
  unit?: RecipeUnit;
  /** Anzeigename, falls er vom Food-Namen abweicht ("Eier", "Joghurt"). */
  name?: string;
  optional?: boolean;
  note?: string;
  /** Gewicht der Menge in g, wenn es vom Standard des Foods abweicht. */
  grams?: number;
}

export interface RecipeSeed {
  slug: string;
  name: string;
  description: string;
  servings: number;
  tags: string[];
  ingredients: IngredientSeed[];
  instructions: string[];
  prepMin: number;
  cookMin: number;
  cuisine?: string;
  equipment: string[];
  /** Nur setzen, wenn eine belastbare Lagerangabe existiert. */
  storageDays?: number;
}

const q = (food: string, amount: number, unit: RecipeUnit, extra: Partial<IngredientSeed> = {}): IngredientSeed => ({
  food,
  amount,
  unit,
  ...extra,
});
const g = (food: string, amount: number, extra: Partial<IngredientSeed> = {}) => q(food, amount, "g", extra);
const ml = (food: string, amount: number, extra: Partial<IngredientSeed> = {}) => q(food, amount, "ml", extra);
const pc = (food: string, amount: number, extra: Partial<IngredientSeed> = {}) => q(food, amount, "piece", extra);
const sl = (food: string, amount: number, extra: Partial<IngredientSeed> = {}) => q(food, amount, "slice", extra);
const tl = (food: string, amount: number, extra: Partial<IngredientSeed> = {}) => q(food, amount, "tl", extra);
/** Zutat ohne Mengenangabe ("nach Geschmack"). */
const s = (food: string, extra: Partial<IngredientSeed> = {}): IngredientSeed => ({ food, ...extra });

